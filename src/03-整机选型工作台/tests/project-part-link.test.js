const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const model = require('../js/project-model.js');
const workbenchApp = fs.readFileSync(path.join(__dirname, '../js/app.js'), 'utf8');

const project = model.createProject();
const segment = project.segments[0];
assert.deepEqual(segment.interface.selection.partRef, { partId: '', name: '', model: '', librarySchemaVersion: 2, updatedAt: null });
assert.equal(model.linkPartToSegment(project, segment.id, { id: 'custom-stable', name: '编辑后的球体刀具', model: 'CUT-SPHERE' }), true);
assert.equal(project.segments[0].interface.selection.partRef.partId, 'custom-stable');
assert.equal(project.segments[0].interface.selection.model, 'CUT-SPHERE');
const restored = model.normalizeProject(model.clone(project));
assert.equal(restored.segments[0].interface.selection.partRef.partId, 'custom-stable');
assert.equal(model.unlinkPartFromSegment(restored, restored.segments[0].id), true);
assert.equal(restored.segments[0].interface.selection.partRef.partId, '');
const legacy = model.clone(project);
delete legacy.segments[0].interface.selection.partRef;
legacy.segments[0].interface.selection.partId = 'legacy-part';
delete legacy.project.units[0].segments[0].interface.selection.partRef;
legacy.project.units[0].segments[0].interface.selection.partId = 'legacy-part';
assert.equal(model.normalizeProject(legacy).segments[0].interface.selection.partRef.partId, 'legacy-part');
const { readFinalWorkbenchSource } = require('./helpers/final-workbench-source');
const prototype = readFinalWorkbenchSource();
assert.match(prototype, /function renderInputs\(\).*\$\{partPickerMarkup\(s\)\}/, 'ThreeJS workbench input panel must render the part-library picker');
assert.match(prototype, /function linkedPartMarkup\(s\)/, 'ThreeJS workbench must render linked customScene geometry');
assert.match(prototype, /data-part-ref="true"/, 'part selection changes must be handled by the workbench');
assert.match(prototype, /统一坐标方向/, 'workbench must display the part-library mounting convention');
const threePreview = fs.readFileSync(path.join(__dirname, '../js/three-preview.js'), 'utf8');
assert.match(threePreview, /function addLinkedPart\(group,segment,length\)/, 'real Three.js workbench must load linked part customScene geometry');
assert.match(threePreview, /if \(addLinkedPart\(group, segment, length\)\) return;/, 'linked geometry must replace the generic segment interior');
assert.match(threePreview, /partLibraryRevision\(\)/, 'saved part-library changes must invalidate the workbench model cache');
assert.match(threePreview, /function linkedMountingQuaternion\(part\)/, 'linked geometry must map the part-library axes into workbench axes');
assert.match(threePreview, /wrapper\.quaternion\.copy\(linkedMountingQuaternion\(part\)\)/, 'workbench must use the shared mounting-axis definition');
assert.match(workbenchApp, /window\.addEventListener\('focus',refreshPartLibraryWhenVisible\)/, 'workbench must refresh shared parts when its window regains focus');
assert.match(workbenchApp, /document\.addEventListener\('visibilitychange',refreshPartLibraryWhenVisible\)/, 'workbench must refresh shared parts when its tab becomes visible');
assert.match(workbenchApp, /if\(partLibraryRefreshPromise\)return partLibraryRefreshPromise/, 'overlapping refresh triggers must share one in-flight request');
const refreshStart = workbenchApp.indexOf('function refreshPartLibrary(){');
const renderPickerStart = workbenchApp.indexOf('function renderSegmentPartPicker() {', refreshStart);
const pickerStart = workbenchApp.indexOf('function updateExistingSegmentPartPicker(){', refreshStart);
const pickerEnd = workbenchApp.indexOf('function renderField(', pickerStart);
const refreshAndPicker = workbenchApp.slice(refreshStart, renderPickerStart) + workbenchApp.slice(pickerStart, pickerEnd);
assert.doesNotMatch(refreshAndPicker, /renderAll\(\)/, 'refresh must not redraw unsaved workbench inputs');
assert.match(refreshAndPicker, /picker\.value=pendingValue/, 'refresh must preserve the current uncommitted picker value');
assert.doesNotMatch(refreshAndPicker, /M\.linkPartToSegment|M\.unlinkPartFromSegment/, 'refresh must not rewrite a saved project partRef');
console.log('通过：功能段按稳定零件 ID 关联、读取和兼容旧字段正常。');
